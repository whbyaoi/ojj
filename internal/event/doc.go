// Package event 提供单进程 SQLite 可靠事件存储和独立广播订阅。
//
// 发布成功表示事件及匹配投递已提交，不表示业务成功。有限重试允许重复副作用，
// 消费者必须幂等。正文只校验 UTF-8 和字节数，路由只使用结构化外壳。
// 新订阅不重放历史；解绑仍积压；停用才取消积压。过滤器在相同订阅 ID 下不可变。
// 超时回调不能强杀：每个绑定至多一个回调，旧调用不退出则该订阅暂停后续处理。
// 关闭不等待不合作回调；跨关闭重开仍可能有旧回调副作用，强隔离需外部进程。
// 存储异常停止受影响调度，通过 Subscription.Err 和 Store.LastError 可见，
// 可修复存储后重绑恢复；普通日志不输出正文或错误细节。
// 默认保留七天，去重键随完成且过期事件清理；未完成事件绝不自动清理。
// 容量是逻辑记账而非磁盘配额，不自动回收 SQLite 物理文件大小。
// 本包不提供鉴权、历史重放、分布式消费、LLM 或 IM 集成。
package event
